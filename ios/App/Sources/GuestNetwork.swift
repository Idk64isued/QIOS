import Foundation

// The guest's web proxy, and why this app has to take it away.
//
// Preparation bakes a proxy auto-config into every device whose recipe has `web_proxy: true` (all of them in the
// catalog): /usr/share/ltm/proxy.pac, named by the en0 AirPort service in the data volume's
// SystemConfiguration/preferences.plist. The PAC sends everything that isn't a plain host name or a private address to
//
//     PROXY 10.0.2.100:3128; DIRECT
//
// On the Mac that address is real: LightTouchMac runs a proxy helper beside the emulator and hands it to slirp, and
// the guest's old TLS is terminated there. This app has no helper process — the emulator is a library inside it — so
// nothing answers 10.0.2.100:3128 and nothing ever will.
//
// CFNetwork takes the PAC at its word. Every connection first tries the proxy, waits out the connect timeout, and only
// then falls back to DIRECT, per connection, with no negative cache. That is the whole of "it says it's connected but
// everything times out": Cydia taking minutes to list a repo and then failing on install, the App Store spinning,
// Safari loading one page in a minute. The traffic was never broken — it was queued behind a dead proxy.
//
// So on every boot the PAC is replaced with one that always returns DIRECT. It is a 100-byte file on the system
// volume (mounted rw), the device's own copy, regenerated by preparation, and nothing else reads it. The original is
// kept beside it as proxy.pac.ltm-old, and Tweaks can put it back for anyone who wires up a proxy of their own.
//
// This does not give the guest modern TLS — iOS 6 still can't speak to a site that needs TLS 1.2 and a 2016 root — but
// it makes plain HTTP (which is what Cydia's repos and most of what still works serve) as fast as the link allows.

enum GuestProxy {
    static let pac = "/usr/share/ltm/proxy.pac"
    static let backup = pac + ".ltm-old"
    /// Present when the user put the baked PAC back (Tweaks): this device is left alone from then on.
    static let keepProxy = "/usr/share/ltm/.ltm-keep-proxy"
    /// What a dead proxy looks like in a PAC: the address preparation bakes in.
    static let deadProxy = "10.0.2.100:3128"

    /// A PAC that sends everything straight out. Same shape as the baked one, minus the proxy.
    static let direct = """
        function FindProxyForURL(url, host) {
            return "DIRECT";
        }

        """
}

extension GuestAgent {
    /// Takes the unreachable web proxy out of the guest's PAC, so connections stop waiting on 10.0.2.100 before
    /// falling back. Quiet when the device has no PAC, when it has already been done, or when the user put the
    /// original back. Run once the agent answers.
    func fixWebProxy() async {
        guard ops.contains("get"), ops.contains("put") || ops.contains("putpart") else { return }
        if await getFile(GuestProxy.keepProxy) != nil { return }
        guard let current = await getFile(GuestProxy.pac), !current.isEmpty else { return }
        let text = String(decoding: current, as: UTF8.self)
        // Already direct (this ran on an earlier boot, or a recipe baked no proxy).
        guard text.contains(GuestProxy.deadProxy) else { return }

        // Keep the original once, so Tweaks can put it back.
        if await getFile(GuestProxy.backup) == nil {
            _ = await putData(current, guestPath: GuestProxy.backup, mode: "0644")
        }
        guard await putData(Data(GuestProxy.direct.utf8), guestPath: GuestProxy.pac, mode: "0644") else {
            log("Web proxy: couldn\u{2019}t rewrite \(GuestProxy.pac); the internet will be slow. \(lastLog)")
            return
        }
        await sync()
        log("Web proxy: the device was pointed at a proxy that isn\u{2019}t here (\(GuestProxy.deadProxy)); "
            + "its connections now go straight out")
    }

    /// Whether this device's PAC was rewritten (so Tweaks can offer to put the baked one back).
    func hasRewrittenProxy() async -> Bool {
        let backup = await getFile(GuestProxy.backup)
        let kept = await getFile(GuestProxy.keepProxy)
        return backup != nil && kept == nil
    }

    /// Puts preparation's own PAC back and keeps it (the fix skips this device from then on).
    func restoreWebProxy() async -> Bool {
        guard let old = await getFile(GuestProxy.backup), !old.isEmpty else { return false }
        guard await putData(Data("kept by the user\n".utf8), guestPath: GuestProxy.keepProxy) else { return false }
        guard await putData(old, guestPath: GuestProxy.pac, mode: "0644") else { return false }
        await sync()
        log("Web proxy: the prepared PAC is back, and stays")
        return true
    }
}
